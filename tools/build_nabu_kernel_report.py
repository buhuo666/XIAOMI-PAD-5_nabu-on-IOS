#!/usr/bin/env python3
"""Build a bounded, freestanding AArch64 report blob using local LLVM only."""
import argparse
import hashlib
import json
from pathlib import Path
import subprocess

ROOT = Path(__file__).resolve().parents[1]


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument('--output', type=Path, required=True)
    ap.add_argument('--work', type=Path, required=True)
    a = ap.parse_args()
    a.work.mkdir(parents=True, exist_ok=True)
    linker = a.work/'report.ld'
    linker.write_text('''ENTRY(kernel_report_start)
SECTIONS {
 . = 0;
 .text : { *(.text.entry) *(.text .text.*) }
 .rodata : { *(.rodata .rodata.*) }
 . = ALIGN(8);
 .data : { *(.data.config) *(.data .data.*) }
 .bss (NOLOAD) : { *(.bss .bss.* COMMON) }
 . = ALIGN(16);
 kernel_report_stack_bottom = .;
 . += 4096;
 kernel_report_stack_top = .;
 ASSERT(. <= 16384, "report exceeds reserved 16 KiB")
 /DISCARD/ : { *(.comment .note.* .eh_frame*) }
}
''')
    inputs = []
    objects = []
    for name in ('NabuKernelReport.c', 'NabuKernelReport.S'):
        src = ROOT/'patches/darwinboot'/name
        obj = a.work/(name + '.o')
        command = ['clang', '--target=aarch64-none-elf', '-Os', '-ffreestanding',
                   '-fpie', '-fno-builtin', '-fno-stack-protector',
                   '-fno-unwind-tables', '-fno-asynchronous-unwind-tables',
                   '-mgeneral-regs-only', '-mno-outline-atomics', '-Wall', '-Wextra', '-Werror',
                   '-c', str(src), '-o', str(obj)]
        subprocess.run(command, check=True)
        objects.append(obj)
        inputs.append({'path': str(src), 'sha256': hashlib.sha256(src.read_bytes()).hexdigest()})
    elf, blob = a.work/'report.elf', a.work/'report.bin'
    subprocess.run(['ld.lld', '-T', str(linker), '--no-undefined', '-o', str(elf), *map(str, objects)], check=True)
    assert not subprocess.check_output(['llvm-nm', '-u', str(elf)]).strip()
    reloc = subprocess.check_output(['llvm-readelf', '-r', str(elf)], text=True)
    assert 'There are no relocations' in reloc
    symbols = {}
    for line in subprocess.check_output(['llvm-nm', '--defined-only', str(elf)], text=True).splitlines():
        addr, _, name = line.split()
        symbols[name] = int(addr, 16)
    assert symbols['kernel_report_start'] == 0
    subprocess.run(['llvm-objcopy', '-O', 'binary', str(elf), str(blob)], check=True)
    data = blob.read_bytes()
    assert symbols['kernel_report_config'] + 109 * 8 <= len(data) <= symbols['kernel_report_stack_bottom']
    assert symbols['kernel_report_stack_top'] <= 16384
    lines = [', '.join(f'0x{x:02x}' for x in data[i:i+16]) for i in range(0, len(data), 16)]
    a.output.parent.mkdir(parents=True, exist_ok=True)
    a.output.write_text('// Generated by build_nabu_kernel_report.py; do not edit.\n'
                       '#define NABU_KERNEL_REPORT_RESERVE 16384U\n'
                       f'#define NABU_KERNEL_REPORT_CONFIG {symbols["kernel_report_config"]}U\n'
                       'STATIC CONST UINT8 mNabuKernelReport[] = {\n  ' + ',\n  '.join(lines) + '\n};\n')
    report = {'inputs': inputs, 'symbols': symbols, 'blob_bytes': len(data),
              'blob_sha256': hashlib.sha256(data).hexdigest(), 'reserve_bytes': 16384,
              'scope': 'screen-only terminal callback; never restores or calls UEFI'}
    (a.work/'report.json').write_text(json.dumps(report, indent=2)+'\n')
    print(json.dumps({'blob_bytes': len(data), 'config_offset': symbols['kernel_report_config'],
                      'stack_top': symbols['kernel_report_stack_top']}))


if __name__ == '__main__':
    main()
